import type { SemanticValue, ThemeEntry, ThemeKind, TokenRule } from './model';

const SCOPES: Record<string, string[]> = {
  comment: ['comment', 'punctuation.definition.comment'],
  string: ['string'],
  escape: ['constant.character.escape'],
  regexp: ['string.regexp'],
  number: ['constant.numeric'],
  constant: ['constant.language'],
  keyword: ['keyword', 'keyword.other'],
  control: ['keyword.control'],
  module: ['keyword.other.import', 'keyword.other.package'],
  storage: ['storage', 'storage.modifier'],
  primitive: ['storage.type.primitive', 'support.type.primitive'],
  operator: ['keyword.operator'],
  punctuation: ['punctuation'],
  type: ['entity.name.type', 'support.class', 'storage.type'],
  function: ['entity.name.function', 'meta.function-call'],
  variable: ['variable', 'variable.other'],
  definition: ['variable.other.definition'],
  property: ['variable.other.property', 'support.type.property-name'],
  self: ['variable.language'],
  label: ['entity.name.label'],
  annotation: ['storage.type.annotation', 'meta.annotation'],
  heading: ['markup.heading', 'entity.name.section'],
  tag: ['entity.name.tag'],
  invalid: ['invalid'],
  builtin: ['support.function', 'support.variable', 'support.constant'],
  link: ['markup.underline.link']
};

type Palette = Record<keyof typeof SCOPES, string | [string, string]>;

function tokenColors(p: Palette): TokenRule[] {
  return Object.entries(p).map(([cat, v]) => {
    const [foreground, fontStyle] = Array.isArray(v) ? v : [v, ''];
    return { name: cat, scope: SCOPES[cat], settings: { foreground, fontStyle } };
  });
}

function builtin(id: string, name: string, type: ThemeKind, colors: Record<string, string>, palette: Palette, semanticTokenColors: Record<string, SemanticValue>, attribution?: string): ThemeEntry {
  return {
    id,
    name,
    author: attribution ? 'One Dark contributors' : 'Modsmith',
    type,
    source: { kind: 'builtin', attribution },
    theme: { colors, tokenColors: tokenColors(palette), semanticTokenColors, semanticHighlighting: true },
    warnings: []
  };
}

