export interface JdtClass {
  uri: string;
  container: string;
  containerPath: string | null;
  project: string | null;
  pkg: string;
  binaryName: string;
  className: string;
  qualifiedName: string;
  module: boolean;
}

const unescapeMemento = (s: string) => s.replace(/\\(.)/g, '$1');

export function parseJdtUri(uri: string): JdtClass | null {
  const m = /^jdt:\/\/contents\/([^?#]+)(?:\?([^#]*))?/.exec(uri);
  if (!m) return null;
  const parts = m[1].split('/').map((p) => {
    try {
      return decodeURIComponent(p);
    } catch {
      return p;
    }
  });
  if (parts.length < 2) return null;
  const file = parts[parts.length - 1];
  if (!/\.(class|java)$/.test(file)) return null;
  const container = parts[0];
  const pkg = parts.slice(1, -1).join('.');
  const binaryName = file.replace(/\.(class|java)$/, '');
  const className = binaryName.split('$')[0];
  let containerPath: string | null = null;
  let project: string | null = null;
  if (m[2]) {
    let q = m[2];
    try {
      q = decodeURIComponent(q);
    } catch {
      return null;
    }
    const handle = q.replace(/^=/, '');
    const slash = handle.search(/(?<!\\)\//);
    if (slash > 0) {
      project = unescapeMemento(handle.slice(0, slash));
      const rest = handle.slice(slash + 1);
      const end = rest.search(/(?<!\\)[<=]/);
      const raw = unescapeMemento(end >= 0 ? rest.slice(0, end) : rest);
      if (raw) containerPath = raw;
    }
  }
  const module = !/\.(jar|zip)$/i.test(container) && /^[a-z][\w]*(\.[a-z][\w]*)*$/.test(container);
  return { uri, container, containerPath, project, pkg, binaryName, className, qualifiedName: pkg ? `${pkg}.${className}` : className, module };
}

export function fileUriToPath(uri: string): string | null {
  if (!uri.startsWith('file://')) return null;
  let rest = uri.slice(7);
  if (rest.startsWith('localhost/')) rest = rest.slice(9);
  let decoded: string;
  try {
    decoded = decodeURIComponent(rest);
  } catch {
    return null;
  }
  if (/^\/[A-Za-z]:\//.test(decoded)) return decoded.slice(1).replace(/\//g, '\\');
  return decoded;
}

export function projectRelative(uri: string, rootUri: string): string | null {
  const file = fileUriToPath(uri);
  const root = fileUriToPath(rootUri);
  if (!file || !root) return null;
  const windows = /^[A-Za-z]:\\/.test(root);
  const norm = (p: string) => p.replace(/\\/g, '/').replace(/\/+$/, '');
  const f = norm(file);
  const r = norm(root);
  const same = (a: string, b: string) => (windows ? a.toLowerCase() === b.toLowerCase() : a === b);
  if (f.length <= r.length + 1 || !same(f.slice(0, r.length), r) || f[r.length] !== '/') return null;
  const rel = f.slice(r.length + 1).split('/');
  if (rel.some((p) => p === '' || p === '.' || p === '..')) return null;
  return rel.join('/');
}

export type SourceOrigin = 'source' | 'decompiled';

export function sourceOrigin(content: string): SourceOrigin {
  const head = content.slice(0, 600);
  return /stub sources have been generated|Implementation of methods is unavailable|generated by the (?:Fernflower|CFR|Procyon|disassembler)|decompiled from a \.class file|^\s*\/\/ Decompiled/im.test(head) ? 'decompiled' : 'source';
}

export function sourceTabTitle(uri: string): string {
  const jdt = parseJdtUri(uri);
  if (jdt) return `${jdt.className}.class`;
  const p = fileUriToPath(uri);
  return p ? (p.split(/[\\/]/).pop() ?? uri) : uri;
}

export function containerLabel(jdt: JdtClass): string {
  if (jdt.module) return `JDK module ${jdt.container}`;
  return jdt.container;
}
