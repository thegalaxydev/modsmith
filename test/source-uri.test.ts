import { describe, expect, it } from 'vitest';
import { Text } from '@codemirror/state';
import { fileUriToPath, parseJdtUri, projectRelative, sourceOrigin, sourceTabTitle } from '../src/renderer/sourceUri';
import { lspToOffset, tabForUri } from '../src/renderer/javaNav';

const ITEM =
  'jdt://contents/neoforge-21.1.72.jar/net.minecraft.world.item/Item$Properties.class?=neo-server/C:%5C/Users%5C/me%5C/.gradle%5C/caches%5C/neoforge-21.1.72.jar%3Cnet.minecraft.world.item(Item$Properties.class';
const STRING = 'jdt://contents/java.base/java.lang/String.class?=neo-server/%5C/opt%5C/jdk-21%5C/lib%5C/jrt-fs.jar%60java.base=/javadoc_location=/https:%5C/%5C/docs.oracle.com%5C/en%5C/java%5C/javase%5C/21%5C/docs%5C/api%5C/=/%3Cjava.lang(String.class';

describe('jdt:// URIs', () => {
  it('reads the class, package and container of a library class', () => {
    expect(parseJdtUri(ITEM)).toMatchObject({
      container: 'neoforge-21.1.72.jar',
      containerPath: 'C:/Users/me/.gradle/caches/neoforge-21.1.72.jar',
      project: 'neo-server',
      pkg: 'net.minecraft.world.item',
      binaryName: 'Item$Properties',
      className: 'Item',
      qualifiedName: 'net.minecraft.world.item.Item',
      module: false
    });
    expect(sourceTabTitle(ITEM)).toBe('Item.class');
  });

  it('reads jdtls URIs of classes with attached sources', () => {
    const uri =
      'jdt://contents/neoforge-21.1.262.jar/net.minecraft.resources/ResourceLocation.java?=neo_server-neo-server/C:%5C/Users%5C/me%5C/neo-server%5C/build%5C/moddev%5C/artifacts%5C/neoforge-21.1.262.jar=/gradle_used_by_scope=/main=/%3Cnet.minecraft.resources%28ResourceLocation.class';
    expect(parseJdtUri(uri)).toMatchObject({
      container: 'neoforge-21.1.262.jar',
      containerPath: 'C:/Users/me/neo-server/build/moddev/artifacts/neoforge-21.1.262.jar',
      project: 'neo_server-neo-server',
      qualifiedName: 'net.minecraft.resources.ResourceLocation'
    });
    expect(sourceTabTitle(uri)).toBe('ResourceLocation.class');
  });

  it('recognises JDK module classes', () => {
    expect(parseJdtUri(STRING)).toMatchObject({ container: 'java.base', pkg: 'java.lang', className: 'String', module: true });
  });

  it('rejects URIs that are not class contents', () => {
    expect(parseJdtUri('jdt://contents/x.jar/a/B.txt')).toBeNull();
    expect(parseJdtUri('jdt://jarentry/x.jar/a/B.class')).toBeNull();
    expect(parseJdtUri('file:///D:/a/B.java')).toBeNull();
    expect(parseJdtUri('jdt://contents/x.jar/B.class?%E0%A4%A')).toBeNull();
  });

  it('opens jdt:// classes as read-only source tabs and project files as file tabs', () => {
    const ctx = { workspace: 'D:\\Mods\\My Mod', rootUri: 'file:///D:/Mods/My%20Mod' };
    expect(tabForUri(ctx, ITEM)).toBe(`src:${ITEM}`);
    expect(tabForUri(ctx, 'file:///d%3A/Mods/My%20Mod/src/main/java/a/B.java')).toBe('file:src/main/java/a/B.java');
    expect(tabForUri(ctx, 'file:///D:/Mods/Other/B.java')).toBeNull();
    expect(tabForUri(ctx, 'file:///D:/Mods/My%20Mod/../Other/B.java')).toBeNull();
    expect(tabForUri(ctx, 'jdt://contents/x.jar/a/B.txt')).toBeNull();
  });
});

describe('file URIs and positions', () => {
  it('converts file URIs to paths and project-relative files', () => {
    expect(fileUriToPath('file:///D:/Mods/My%20Mod/a.java')).toBe('D:\\Mods\\My Mod\\a.java');
    expect(fileUriToPath('file:///home/me/mod/a.java')).toBe('/home/me/mod/a.java');
    expect(projectRelative('file:///home/me/mod/src/A.java', 'file:///home/me/mod')).toBe('src/A.java');
    expect(projectRelative('file:///home/me/modded/A.java', 'file:///home/me/mod')).toBeNull();
    expect(projectRelative('file:///home/Me/mod/A.java', 'file:///home/me/mod')).toBeNull();
    expect(projectRelative('file:///d:/MODS/a/A.java', 'file:///D:/Mods/a')).toBe('A.java');
  });

  it('maps LSP positions into the document and clamps them', () => {
    const doc = Text.of(['class A {', '  int x;', '}']);
    expect(lspToOffset(doc, { line: 1, character: 6 })).toBe(16);
    expect(lspToOffset(doc, { line: 1, character: 99 })).toBe(18);
    expect(lspToOffset(doc, { line: 9, character: 0 })).toBe(19);
  });

  it('tells attached sources from decompiled stubs', () => {
    expect(sourceOrigin('// Failed to get sources. Instead, stub sources have been generated by the disassembler.\n// Implementation of methods is unavailable.\npackage a;')).toBe('decompiled');
    expect(sourceOrigin('// Source code is decompiled from a .class file using FernFlower decompiler (from Intellij IDEA).\npackage net.minecraft.resources;')).toBe('decompiled');
    expect(sourceOrigin('/*\n * Copyright (c) 1994, Oracle\n */\npackage java.lang;')).toBe('source');
  });
});
